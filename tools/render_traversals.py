"""Render traversal views with the existing box/place renderer, without changing geometry."""

import copy
from pathlib import Path

import render
import validate


def outputs(world: dict, directory: Path) -> dict[str, str]:
    result = {}
    rows = []
    diagrams = []
    for traversal in world["traversals"]:
        # Local display roles only. The source world and its neutral names stay intact.
        view = copy.deepcopy(world)
        view["format"] = "livingproof-world/0.2"
        view["title"] += f" — {traversal['name']} traversal"
        aliases = {
            traversal["from"]: "entrance",
            traversal["finish"]: "exit",
            traversal["route"]: "route-centreline",
        }
        for place in view["places"]:
            place["name"] = aliases.get(place["name"], place["name"])
        for mode in ("auto", "light", "dark"):
            svg = render.render_svg(view, mode)
            # IN/OUT describe this explicitly selected traversal, not endpoint identity.
            for original, alias in aliases.items():
                svg = svg.replace(alias, original)
            result[f"{traversal['name']}-{mode}.svg"] = svg
        length = validate.route_length(world, start=traversal["start"], route=traversal["route"])
        rows.append(
            "| "
            + " | ".join(traversal[k] for k in ("name", "from", "start", "route", "finish"))
            + f" | {length:g} m |"
        )
        diagrams.append(
            f"![{traversal['name']} traversal of the same geometry]({traversal['name']}-auto.svg)"
        )
    places = "\n".join(
        f"| {p['name']} | {p['type']} | {render.coords(p)} |" for p in world["places"]
    )
    dimensions = "\n".join(f"| {key} | {value:g} m |" for key, value in world["dimensions"].items())
    spec = world["specification"]
    dependency = "Unreleased specs dependency; excluded from the release catalog."
    if "tag" in spec:
        dependency = f"Specification: [{spec['tag']}]({render.SPEC_URL.format(**spec)}), commit `{spec['commit']}`."
    result["README.md"] = (
        "<!-- Generated by tools/render.py from world.json and notes.md. -->\n"
        + (directory / "notes.md").read_text()
        + "\n## Purpose\n\nOne physical fixture, with explicitly selected opposite traversals.\n\n"
        + dependency
        + "\n\n## Traversal references\n\n"
        + "| Traversal | From | Start | Route | Finish | Travel |\n"
        + "| --- | --- | --- | --- | --- | --- |\n"
        + "\n".join(rows)
        + "\n\n## Diagram\n\n"
        + "Both views use identical boxes and coordinates. IN and OUT are roles for the named traversal.\n\n"
        + "\n\n".join(diagrams)
        + "\n\n## Dimensions\n\n| Quantity | Value |\n| --- | --- |\n"
        + dimensions
        + "\n\n## Named places\n\n| Name | Type | Definition |\n| --- | --- | --- |\n"
        + places
        + "\n\n## Frame and tolerances\n\nRight-handed, metres; +x east, +y north, +z up. "
        + f"Origin: {world['frame']['origin']}. Yaw is positive about +z. "
        + f"Distance tolerance {world['tolerances']['distance_m']:g} m; angle tolerance {world['tolerances']['angle_deg']:g} degrees.\n"
        + "\n## Version and changelog\n\nContent 0.2.0 adds neutral endpoints and explicit traversals; geometry remains unchanged from 0.1.0.\n"
        + "\n## Provenance and licence\n\n"
        + world["provenance"]["method"]
        + f" Licence: {world['license']}.\n"
        + "\n## Simulator support\n\nStatic contract validation only. Engine and robot execution are unrun.\n"
    )
    return result
